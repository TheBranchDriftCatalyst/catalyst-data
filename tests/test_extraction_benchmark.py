class TestGroundTruth:
    """Generate and validate ground truth from a reference model's output."""

    def test_generate_ground_truth(self):
        """Generate ground truth from the current model's extraction output.

        Only creates the fixture if it doesn't already exist -- won't overwrite
        manually reviewed annotations.
        """
        gt = _store.load_ground_truth("active")
        if gt and gt.get("manually_reviewed"):
            pytest.skip("Ground truth already exists and has been manually reviewed")
            return

        model = _llm_model()
        extraction = _load_fixture(f"extraction_{model}")
        if not extraction:
            pytest.skip(
                f"No extraction fixture for model '{model}'. "
                f"Run: LLM_MODEL={model} pytest tests/test_pipeline_integration.py -k extraction -v -s"
            )
            return

        from tests.shared.medallion import load_chunks

        chunks = load_chunks()
        if not chunks:
            pytest.skip("No chunks materialized. Run `task bench:chunks:regen` first.")
            return

        # Build per-chunk ground truth from extraction output
        mentions_by_chunk: dict[str, list] = {}
        for m in extraction["mentions"]:
            cid = m.get("chunk_id", "")
            mentions_by_chunk.setdefault(cid, []).append(m)

        assertions_by_chunk: dict[str, list] = {}
        for a in extraction["assertions"]:
            prov = a.get("provenance") or {}
            cid = prov.get("chunk_id", "")
            assertions_by_chunk.setdefault(cid, []).append(a)

        gt_chunks = []
        for chunk in chunks:
            cid = chunk["chunk_id"]
            chunk_mentions = mentions_by_chunk.get(cid, [])
            chunk_assertions = assertions_by_chunk.get(cid, [])

            clean_mentions = [
                {
                    "text": m["text"],
                    "mention_type": m["mention_type"],
                    "span_start": m.get("span_start"),
                    "span_end": m.get("span_end"),
                    "confidence": m.get("confidence", 1.0),
                }
                for m in chunk_mentions
            ]
            clean_assertions = [
                {
                    "subject": a.get("subject_text", a.get("subject", "")),
                    "predicate": a.get("predicate", ""),
                    "object": a.get("object_text", a.get("object", "")),
                    "confidence": a.get("confidence", 1.0),
                    "evidence": a.get("evidence", ""),
                }
                for a in chunk_assertions
            ]

            gt_chunks.append(
                {
                    "chunk_id": cid,
                    "text": chunk["text"],
                    "mentions": clean_mentions,
                    "propositions": clean_assertions,
                }
            )

        ground_truth = {
            "domain": "media_ingest",
            "reference_model": model,
            "manually_reviewed": False,
            "chunk_count": len(gt_chunks),
            "total_mentions": sum(len(c["mentions"]) for c in gt_chunks),
            "total_propositions": sum(len(c["propositions"]) for c in gt_chunks),
            "chunks": gt_chunks,
        }

        _store.save_ground_truth("active", ground_truth)
        gt_path = _store.ground_truth_dir / "active.json"
        print(f"\n  Ground truth generated from {model}:")
        print(f"    {len(gt_chunks)} chunks")
        print(f"    {ground_truth['total_mentions']} mentions")
        print(f"    {ground_truth['total_propositions']} propositions")
        print(f"    File: {gt_path}")
        print("\n  *** Review and correct the file, then set manually_reviewed=true ***")

    def test_ground_truth_self_check(self):
        """Validate that all ground truth spans match their source text."""
        gt = _store.load_ground_truth("active")
        if not gt:
            pytest.skip("No ground truth fixture. Run test_generate_ground_truth first.")
            return

        all_errors = []
        for chunk in gt["chunks"]:
            errors = validate_ground_truth(chunk["mentions"], chunk["text"])
            for e in errors:
                all_errors.append(f"  {chunk['chunk_id']}: {e}")

        if all_errors:
            print(f"\n  Ground truth span errors ({len(all_errors)}):")
            for e in all_errors[:20]:
                print(e)

        if gt.get("manually_reviewed"):
            assert not all_errors, f"{len(all_errors)} span errors in reviewed ground truth"
        elif all_errors:
            print(f"\n  WARNING: {len(all_errors)} span errors in unreviewed ground truth")

    def test_generate_ensemble_ground_truth(self):
        """Generate ground truth from consensus across multiple models.

        Uses majority voting: a mention/proposition is accepted as ground truth
        if >= ceil(N/2) models agree on it. This produces more robust ground
        truth than relying on a single model.

        Only creates the fixture if it doesn't already exist or the existing
        one is not manually reviewed.
        """
        existing = _store.load_ground_truth("active")
        if existing and existing.get("manually_reviewed"):
            pytest.skip("Ground truth already exists and has been manually reviewed")
            return

        ground_truth = generate_ensemble_ground_truth(_store)
        if ground_truth is None:
            pytest.skip(
                "Not enough model fixtures for ensemble ground truth (need >= 2). Run extraction benchmarks first."
            )
            return

        _store.save_ground_truth("active", ground_truth)
        gt_path = _store.ground_truth_dir / "active.json"
        config = ground_truth["ensemble_config"]
        print("\n  Ensemble ground truth generated:")
        print(f"    NER models ({len(config['ner_models'])}): {', '.join(config['ner_models'])}")
        print(f"    SPO models ({len(config['spo_models'])}): {', '.join(config['spo_models'])}")
        print(f"    Threshold: {config['threshold']}")
        print(f"    {ground_truth['chunk_count']} chunks")
        print(f"    {ground_truth['total_mentions']} mentions (consensus)")
        print(f"    {ground_truth['total_propositions']} propositions (consensus)")
        print(f"    File: {gt_path}")
        print("\n  *** Review and correct the file, then set manually_reviewed=true ***")


