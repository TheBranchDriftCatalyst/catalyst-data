class TestBenchmark:
    """Score a model's extraction output against ground truth."""

    @pytest.fixture
    def ground_truth(self):
        gt = _store.load_ground_truth("active")
        if not gt:
            pytest.skip("No ground truth fixture. Run test_generate_ground_truth first.")
        return gt

    @pytest.fixture
    def extraction(self):
        model = _llm_model()
        ext = _load_fixture(f"extraction_{model}")
        if not ext:
            pytest.skip(
                f"No extraction fixture for '{model}'. "
                f"Run: LLM_MODEL={model} pytest tests/test_pipeline_integration.py -k extraction -v -s"
            )
        return ext

    def test_benchmark_mentions(self, ground_truth, extraction):
        """Score mention extraction against ground truth."""
        model = extraction["model"]

        gt_mentions = []
        for chunk in ground_truth["chunks"]:
            gt_mentions.extend(chunk["mentions"])

        scores = score_mentions(
            extraction["mentions"],
            gt_mentions,
            source_text=None,
        )

        print(f"\n  Mention Benchmark -- {model} vs ground truth ({ground_truth['reference_model']})")
        print(f"    Predicted: {scores['predicted_count']}  Ground truth: {scores['ground_truth_count']}")
        print(
            f"    Strict  -- P: {scores['strict_precision']:.3f}  "
            f"R: {scores['strict_recall']:.3f}  F1: {scores['strict_f1']:.3f}"
        )
        print(
            f"    Relaxed -- P: {scores['relaxed_precision']:.3f}  "
            f"R: {scores['relaxed_recall']:.3f}  F1: {scores['relaxed_f1']:.3f}"
        )
        print(f"    Type accuracy: {scores['type_accuracy']:.3f}")
        if scores["missed"]:
            print(f"    Missed ({len(scores['missed'])}): {scores['missed'][:5]}")
        if scores["extra"]:
            print(f"    Extra ({len(scores['extra'])}):  {scores['extra'][:5]}")

    def test_benchmark_propositions(self, ground_truth, extraction):
        """Score proposition extraction against ground truth."""
        model = extraction["model"]

        gt_propositions = []
        for chunk in ground_truth["chunks"]:
            gt_propositions.extend(chunk["propositions"])

        scores = score_propositions(extraction["assertions"], gt_propositions)

        print(f"\n  Proposition Benchmark -- {model} vs ground truth ({ground_truth['reference_model']})")
        print(f"    Predicted: {scores['predicted_count']}  Ground truth: {scores['ground_truth_count']}")
        print(
            f"    Strict  -- P: {scores['strict_precision']:.3f}  "
            f"R: {scores['strict_recall']:.3f}  F1: {scores['strict_f1']:.3f}"
        )
        print(
            f"    Relaxed -- P: {scores['relaxed_precision']:.3f}  "
            f"R: {scores['relaxed_recall']:.3f}  F1: {scores['relaxed_f1']:.3f}"
        )
        if scores["missed"]:
            print(f"    Missed ({len(scores['missed'])}): {scores['missed'][:3]}")
        if scores["extra"]:
            print(f"    Extra ({len(scores['extra'])}):  {scores['extra'][:3]}")

    def test_benchmark_summary(self, ground_truth, extraction):
        """Print full benchmark summary with both mention and proposition scores."""
        model = extraction["model"]

        gt_mentions = []
        gt_propositions = []
        for chunk in ground_truth["chunks"]:
            gt_mentions.extend(chunk["mentions"])
            gt_propositions.extend(chunk["propositions"])

        m_scores = score_mentions(extraction["mentions"], gt_mentions)
        p_scores = score_propositions(extraction["assertions"], gt_propositions)

        print_scores(m_scores, p_scores, model=model)


