LEGACY_FIXTURES = Path(__file__).parent / "fixtures"

pytestmark = pytest.mark.llm


def _llm_model() -> str:
    return os.environ.get("LLM_MODEL", "gpt-4o-mini")


def _load_fixture(name: str) -> dict | list | None:
    """Load a fixture by name. Thin wrapper around BenchmarkStore for backward compat."""
    return _store.load_fixture(name)


def _save_fixture(name: str, data):
    """Save a fixture by name. Thin wrapper around BenchmarkStore for backward compat."""
    _store.save_fixture(name, data)


