"""Extraction benchmark — ground truth generation and model comparison.

Two-phase workflow:

Phase 1: Generate reference ground truth (run once with a strong model):
    LLM_MODEL=gpt-4o OPENAI_API_KEY=xxx \\
        pytest tests/test_extraction_benchmark.py -k "generate_ground_truth" -v -s

    This creates tests/fixtures/ground_truth_media_ingest.json with
    manually_reviewed=false. Open the file, review/correct annotations,
    then set manually_reviewed=true.

Phase 2: Benchmark other models against ground truth:
    LLM_MODEL=gpt-4o-mini OPENAI_API_KEY=xxx \\
        pytest tests/test_extraction_benchmark.py -k "benchmark" -v -s

    This loads extraction_{model}.json (generated by test_pipeline_integration.py)
    and scores it against the ground truth fixture.

Run all models and compare:
    for model in gpt-4o-mini gpt-4o claude-3-5-sonnet; do
        LLM_MODEL=$model pytest tests/test_extraction_benchmark.py -v -s
    done
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import pytest

from tests.shared.extraction_scoring import (
    print_comparison_table,
    print_scores,
    score_mentions,
    score_propositions,
    validate_ground_truth,
)

REPO_ROOT = Path(__file__).resolve().parents[0] / ".."
TEST_OUTPUT = Path(os.environ.get("TEST_OUTPUT_ROOT", str(REPO_ROOT / ".test-output"))) / "media-ingest"
FIXTURES = TEST_OUTPUT / "fixtures"
# Fallback for curated files still in tests/fixtures/
LEGACY_FIXTURES = Path(__file__).parent / "fixtures"

pytestmark = pytest.mark.llm


def _llm_model() -> str:
    return os.environ.get("LLM_MODEL", "gpt-4o-mini")


def _load_fixture(name: str) -> dict | list | None:
    f = FIXTURES / f"{name}.json"
    if f.exists():
        return json.loads(f.read_text())
    # Fallback to legacy location
    f2 = LEGACY_FIXTURES / f"{name}.json"
    return json.loads(f2.read_text()) if f2.exists() else None


def _save_fixture(name: str, data):
    FIXTURES.mkdir(exist_ok=True)
    (FIXTURES / f"{name}.json").write_text(json.dumps(data, indent=2, default=str))


