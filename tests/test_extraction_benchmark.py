class TestRunAll:
    """Run extraction benchmarks across all models defined in benchmark_config.py.

    Usage:
        PYTHONPATH=. pytest tests/test_extraction_benchmark.py::TestRunAll -v -s
        PYTHONPATH=. pytest tests/test_extraction_benchmark.py::TestRunAll -v -s --regen

    Pass --regen to force regenerate all fixtures (ignore cached results).
    """

    def test_run_all_models(self, request):
        """Run extraction for every model in benchmark_config.ALL_MODELS."""
        import subprocess
        import sys
        import urllib.request

        from tests.benchmark_config import ALL_MODELS

        regen = request.config.getoption("--regen", default=False)
        timeout_override = request.config.getoption("--timeout", default=None)
        save_audit = request.config.getoption("--audit-log", default=False)
        pipeline = "exgraph v2" if os.environ.get("EXGRAPH_ENABLED", "").lower() == "true" else "v1 (legacy)"

        # Print run summary
        print(f"\n{'=' * 70}")
        print(f"  Extraction Benchmark — {len(ALL_MODELS)} models")
        print(f"  Pipeline: {pipeline} | Timeout: {timeout_override or 300}s | Regen: {regen} | Audit: {save_audit}")
        print(f"{'=' * 70}")

        encoders = [m for m in ALL_MODELS if "encoder" in m.tags]
        specialists = [m for m in ALL_MODELS if "extraction-specialist" in m.tags and "encoder" not in m.tags]
        llms = [
            m
            for m in ALL_MODELS
            if "cloud" not in m.tags and "encoder" not in m.tags and "extraction-specialist" not in m.tags
        ]
        cloud = [m for m in ALL_MODELS if "cloud" in m.tags]

        if encoders:
            print(f"\n  Encoders ({len(encoders)}):")
            for m in encoders:
                print(f"    {m.name:<22} {m.model}")
        if specialists:
            print(f"\n  Specialists ({len(specialists)}):")
            for m in specialists:
                print(f"    {m.name:<22} {m.model}")
        if llms:
            print(f"\n  Local LLMs ({len(llms)}):")
            for m in llms:
                print(f"    {m.name:<22} {m.model}")
        if cloud:
            print(f"\n  Cloud ({len(cloud)}):")
            for m in cloud:
                print(f"    {m.name:<22} {m.model}")
        print()

        if regen:
            print("  --regen: will clear each model fixture before re-running")
        if timeout_override:
            print(f"  --timeout: {timeout_override}s per model")

        # Audit log directory — wipe and recreate if flag is set
        audit_dir = FIXTURES.parent / "audit-logs"
        if save_audit:
            import shutil

            if audit_dir.exists():
                shutil.rmtree(audit_dir)
            audit_dir.mkdir(parents=True, exist_ok=True)
            print(f"  --audit-log: saving to {audit_dir}")

        chunks = _load_fixture("chunks")
        if not chunks:
            pytest.skip("No chunks fixture. Run test_pipeline_integration.py first.")
            return

        results = []
        for cfg in ALL_MODELS:
            # Skip cloud models if no API key
            if "cloud" in cfg.tags:
                api_key = cfg.api_key or os.environ.get("LLM_API_KEY", "") or os.environ.get("OPENAI_API_KEY", "")
                if not api_key:
                    print(f"\n  SKIP {cfg.name}: LLM_API_KEY / OPENAI_API_KEY not set")
                    continue

            # Check if endpoint is reachable (skip for encoder models like GLiNER)
            if cfg.base_url and "cloud" not in cfg.tags:
                try:
                    req = urllib.request.Request(f"{cfg.base_url}/models", method="GET")
                    urllib.request.urlopen(req, timeout=3)
                except Exception:
                    print(f"\n  SKIP {cfg.name}: endpoint {cfg.base_url} not reachable")
                    continue

            # Clear this model's fixture if --regen
            if regen:
                fixture_path = FIXTURES / f"extraction_{cfg.model}.json"
                if fixture_path.exists():
                    fixture_path.unlink()

            # Check if we already have a fixture for this model
            cached = _load_fixture(f"extraction_{cfg.model}")
            if cached:
                s = cached.get("stats", {})
                print(
                    f"\n  CACHED {cfg.name}: {s.get('mention_count', '?')} mentions, "
                    f"{s.get('assertion_count', '?')} assertions, "
                    f"{s.get('duration_s', '?')}s, {s.get('mention_retries', '?')} retries"
                )
                results.append({"model": cfg.name, "fixture": cached, "tags": cfg.tags})
                continue

            print(f"\n  RUNNING {cfg.name} ({cfg.model}) via {cfg.base_url or 'in-process'}...")

            # Run as subprocess to isolate env vars per model.
            # CRITICAL: for local models, override LLM_BASE_URL and LLM_API_KEY
            # to prevent the parent env's litellm config from leaking through.
            is_cloud = "cloud" in cfg.tags
            if is_cloud:
                api_key = cfg.api_key or os.environ.get("LLM_API_KEY", "") or os.environ.get("OPENAI_API_KEY", "")
                base_url = cfg.base_url
            else:
                api_key = "unused"
                base_url = cfg.base_url or "http://localhost:11434/v1"

            env = {
                **os.environ,
                "LLM_MODEL": cfg.model,
                "LLM_BASE_URL": base_url,
                "LLM_API_KEY": api_key,
                "OPENAI_API_KEY": api_key,
                "SAVE_AUDIT_LOG": "true" if save_audit else "",
                "LLM_STRUCTURED_METHOD": cfg.structured_method,
                "LLM_MAX_TOKENS": str(cfg.max_tokens),
                "LLM_TIMEOUT": str(timeout_override or cfg.timeout),
                "PROMPT_REGISTRY_DIR": str(Path(__file__).resolve().parent.parent / "k8s" / "shared" / "prompts"),
                "PYTHONPATH": str(Path(__file__).resolve().parent.parent),
            }

            try:
                proc = subprocess.run(
                    [
                        sys.executable,
                        "-m",
                        "pytest",
                        "tests/test_pipeline_integration.py",
                        "-k",
                        "extraction_produces_mentions",
                        "-v",
                        "-s",
                        "--no-header",
                        "--tb=short",
                    ],
                    env=env,
                    capture_output=True,
                    text=True,
                    timeout=timeout_override or cfg.timeout,
                    cwd=str(Path(__file__).resolve().parent.parent),
                )
            except subprocess.TimeoutExpired:
                print(f"  TIMEOUT {cfg.name}: exceeded {cfg.timeout}s — skipping")
                continue

            if proc.returncode == 0:
                fixture = _load_fixture(f"extraction_{cfg.model}")
                if fixture:
                    results.append({"model": cfg.name, "fixture": fixture, "tags": cfg.tags})
                    s = fixture.get("stats", {})
                    # Print detailed results
                    print(
                        f"  OK {cfg.name}: {s.get('mention_count', 0)} mentions, "
                        f"{s.get('assertion_count', 0)} assertions, "
                        f"{s.get('duration_s', 0)}s, "
                        f"{s.get('tokens_per_sec', 0)} tok/s, "
                        f"{s.get('mention_retries', 0)} retries, "
                        f"{s.get('errors', 0)} errors"
                    )
                    # Print extracted entities
                    types: dict[str, int] = {}
                    for m in fixture.get("mentions", []):
                        t = m.get("mention_type", "?")
                        types[t] = types.get(t, 0) + 1
                    if types:
                        type_str = ", ".join(f"{t}:{c}" for t, c in sorted(types.items(), key=lambda x: -x[1]))
                        print(f"  Types: {type_str}")
                    # Show top entities
                    top = fixture.get("mentions", [])[:8]
                    if top:
                        ents = [f"{m.get('text', '?')}" for m in top]
                        print(f"  Top entities: {', '.join(ents)}")

                    # Save structured audit log per model
                    if save_audit:
                        audit_events = s.get("audit_events", [])
                        if audit_events:
                            safe_name = cfg.name.replace("/", "_").replace(":", "_").replace(" ", "_")
                            audit_file = audit_dir / f"{safe_name}.json"
                            audit_data = {
                                "model": cfg.model,
                                "name": cfg.name,
                                "tags": cfg.tags,
                                "stats": {k: v for k, v in s.items() if k != "audit_events"},
                                "audit_events": audit_events,
                                "event_count": len(audit_events),
                                "stages": sorted({e.get("node_name", "?") for e in audit_events}),
                            }
                            with open(audit_file, "w") as f:
                                json.dump(audit_data, f, indent=2, default=str)
                            print(f"  Audit log: {audit_file.name} ({len(audit_events)} events)")
                    # Save incremental report so cancelled runs have partial results
                    _save_incremental_report(results)
                else:
                    print(f"  WARN {cfg.name}: test passed but no fixture saved")
            else:
                # Show the failure details
                stderr_tail = proc.stderr[-300:] if proc.stderr else ""
                stdout_tail = proc.stdout[-300:] if proc.stdout else ""
                print(f"  FAIL {cfg.name}")
                if "FAILED" in stdout_tail:
                    # Extract the failure reason
                    for line in stdout_tail.split("\n"):
                        if "FAILED" in line or "Error" in line or "assert" in line:
                            print(f"    {line.strip()}")
                elif stderr_tail:
                    print(f"    stderr: {stderr_tail[:200]}")

        # Print comparison if we have ground truth
        gt = _load_fixture("ground_truth_media_ingest")
        if gt and results:
            gt_mentions = []
            gt_propositions = []
            for chunk in gt["chunks"]:
                gt_mentions.extend(chunk["mentions"])
                gt_propositions.extend(chunk["propositions"])

            scored = []
            for r in results:
                ext = r["fixture"]
                m_scores = score_mentions(ext["mentions"], gt_mentions)
                p_scores = score_propositions(ext.get("assertions", []), gt_propositions)
                scored.append(
                    {
                        "model": r["model"],
                        "mention_scores": m_scores,
                        "proposition_scores": p_scores,
                        "stats": ext.get("stats", {}),
                    }
                )
            print_comparison_table(scored)
        # Full benchmark report: entity matrix, SPO matrix, stats by type
        if results:
            print_benchmark_report(results)

            # Save structured JSON report for the viewer-ui SPA
            report = _build_report_json(results)
            report_path = FIXTURES.parent / "benchmark-report.json"
            report_path.parent.mkdir(parents=True, exist_ok=True)
            with open(report_path, "w") as f:
                json.dump(report, f, indent=2, default=str)
            print(f"  Report saved: {report_path}")

            if not gt:
                print(
                    "  No ground truth yet. Generate with: "
                    "pytest tests/test_extraction_benchmark.py -k generate_ground_truth -v -s\n"
                )
