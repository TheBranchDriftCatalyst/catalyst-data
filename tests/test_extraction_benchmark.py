"""Extraction benchmark -- ground truth generation and model comparison.

Two-phase workflow:

Phase 1a: Generate reference ground truth from a single model:
    LLM_MODEL=gpt-4o OPENAI_API_KEY=xxx \\
        pytest tests/test_extraction_benchmark.py -k "generate_ground_truth" -v -s

Phase 1b: Generate ensemble ground truth from multi-model consensus:
    pytest tests/test_extraction_benchmark.py -k "ensemble_ground_truth" -v -s

    Or via the harness:
    python tests/benchmark_harness.py --ensemble-gt

    Uses majority voting across available extraction fixtures.
    Requires >= 2 model fixtures to exist.

    This creates ground truth in .test-output/media-ingest/ground-truth/active.json
    with manually_reviewed=false. Review/correct annotations, then set
    manually_reviewed=true.

Phase 2: Benchmark other models against ground truth:
    LLM_MODEL=gpt-4o-mini OPENAI_API_KEY=xxx \\
        pytest tests/test_extraction_benchmark.py -k "benchmark" -v -s

    This loads extraction_{model}.json (generated by test_pipeline_integration.py)
    and scores it against the ground truth fixture.

Run all models:
    python tests/benchmark_harness.py --full

    (TestRunAll has been removed -- use benchmark_harness.py instead)
"""

from __future__ import annotations

import os
from pathlib import Path

import pytest

from tests.shared.extraction_scoring import (
    print_comparison_table,
    print_scores,
    score_mentions,
    score_propositions,
    validate_ground_truth,
)
from tests.shared.ground_truth import generate_ensemble_ground_truth
from tests.shared.store import BenchmarkStore

# Shared store instance for this module
_store = BenchmarkStore()

# Legacy path constants (kept for reference / backward compat)
REPO_ROOT = Path(__file__).resolve().parents[0] / ".."
TEST_OUTPUT = Path(os.environ.get("TEST_OUTPUT_ROOT", str(REPO_ROOT / ".test-output"))) / "media-ingest"
FIXTURES = TEST_OUTPUT / "fixtures"

