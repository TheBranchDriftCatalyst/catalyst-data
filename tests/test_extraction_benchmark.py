class TestComparison:
    """Compare all available model extraction fixtures against ground truth."""

    def test_compare_all_models(self):
        """Load all extraction_*.json fixtures and score each against ground truth."""
        gt = _load_fixture("ground_truth_media_ingest")
        if not gt:
            pytest.skip("No ground truth fixture.")
            return

        gt_mentions = []
        gt_propositions = []
        for chunk in gt["chunks"]:
            gt_mentions.extend(chunk["mentions"])
            gt_propositions.extend(chunk["propositions"])

        # Find all extraction fixtures
        extraction_files = sorted(FIXTURES.glob("extraction_*.json"))
        if not extraction_files:
            pytest.skip("No extraction fixtures found.")
            return

        results = []
        for f in extraction_files:
            ext = json.loads(f.read_text())
            model = ext.get("model", f.stem.replace("extraction_", ""))
            m_scores = score_mentions(ext["mentions"], gt_mentions)
            p_scores = score_propositions(ext.get("assertions", []), gt_propositions)
            results.append(
                {
                    "model": model,
                    "mention_scores": m_scores,
                    "proposition_scores": p_scores,
                    "stats": ext.get("stats", {}),
                }
            )

        print_comparison_table(results)


